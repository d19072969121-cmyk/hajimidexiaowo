/**
 * 错题归类体系（E5）
 *
 * ## 为什么要重做（用户反馈）
 * 旧实现让模型**自由发明标签**（提示词只说「标签是具体知识点，如一元二次方程」
 * 并给 1-5 个），结果每题产出的标签都不一样、没有层级、无法用来筛选——
 * 用户原话是「你预设的标签都是什么鬼」。
 *
 * ## 新体系（用户指定的三层优先级）
 * 归类时的标签来源，**严格按以下顺序**：
 *
 *   ① **用户已有标签**（最高优先）
 *      模型只能从用户现有的标签集合里挑。理由：用户自己的体系才有一致性，
 *      让模型另造新词会让标签库无限膨胀且互相近义。
 *
 *   ② **体系内固定项**（次优先）
 *      用户标签里没有适配项时，从下面三组固定体系里选：
 *        - 学科：语数英物化生政史地（用户明确要求这九类）
 *        - 知识点类型：概念/公式/计算/推理/实验/应用/识记
 *        - 错误原因：复用项目既有的 ErrorCause 体系
 *
 *   ③ **新增标签**（最后手段）
 *      前两层都无适配时才允许新增。提示词里明确要求「实在没有再新增」，
 *      以此抑制标签库膨胀。
 *
 * ## 学科标签「是否出现由用户决定」
 * 用户原话：「是否出现这标签由用户决定」——即学科标签不是自动打给每道题的，
 * 而是**当用户已有学科类标签、或被归入体系时才用**。因此学科枚举只作为
 * 「可选池」提供给模型，不强制每题必带学科标签。
 */

/** 九个学科（用户指定：语数英物化生政史地） */
export const SUBJECT_TAGS = [
  '语文', '数学', '英语', '物理', '化学', '生物', '政治', '历史', '地理',
] as const;

/**
 * 知识点类型。
 *
 * 描述「这道题考的是什么能力维度」，与学科正交——一道数学题可以是
 * 「数学 + 计算」，也可以是「数学 + 推理」。
 */
export const KNOWLEDGE_TYPE_TAGS = [
  '概念理解', '公式运用', '计算求解', '推理论证', '实验探究', '实际应用', '记忆背诵',
] as const;

/**
 * 错误原因标签。
 *
 * 与项目既有的 ErrorCause 体系（`src/components/review/errorCauseRules.ts`）
 * **刻意区分**：那套是**从答题数据自动推导**的（attempts/correct 统计），
 * 是客观指标；本套是**从题目与解析内容判断**的，是内容层面的错因分类，
 * 由模型给出。两者维度不同，可以并存。
 */
export const ERROR_CAUSE_TAGS = [
  '审题失误', '概念混淆', '公式记错', '计算错误', '思路缺失', '粗心大意',
] as const;

/** 全部体系内固定标签（供 UI 展示与搜索） */
export const SYSTEM_TAGS: readonly string[] = [
  ...SUBJECT_TAGS,
  ...KNOWLEDGE_TYPE_TAGS,
  ...ERROR_CAUSE_TAGS,
];

/**
 * 构造归类提示词（三层优先级）。
 *
 * @param question 题干
 * @param answer 解析
 * @param userTags 用户**已有**的标签集合（最高优先的来源）
 */
export function buildClassifyPrompt(
  question: string,
  answer: string,
  userTags: readonly string[] = [],
): string {
  const q = (question ?? '').slice(0, 1000).trim();
  const a = (answer ?? '').slice(0, 2000).trim();
  const existing = [...new Set(userTags.map((t) => t.trim()).filter(Boolean))];

  const existingBlock = existing.length > 0
    ? `用户已有的标签（**优先从这里选**）：\n${existing.join('、')}`
    : '用户目前还没有任何标签。';

  return [
    '你是学习错题归类助手。请为下面这道题挑选 1-4 个标签。',
    '',
    '【选择顺序，必须严格遵守】',
    '① **优先从「用户已有的标签」里选**。只要其中有与本题相符的，就只用这些，',
    '   不要另造新词。这是最重要的一条。',
    '② 用户标签里确实没有合适的，再从下面的固定体系里选：',
    `   - 学科：${SUBJECT_TAGS.join('、')}`,
    `   - 知识点类型：${KNOWLEDGE_TYPE_TAGS.join('、')}`,
    `   - 错误原因：${ERROR_CAUSE_TAGS.join('、')}`,
    '③ 仅当前两层都没有适配项时，才允许新增一个具体知识点标签',
    '   （如「一元二次方程」「定语从句」）。**能不加就不加。**',
    '',
    `【数量】最多 ${MAX_AUTO_TAGS} 个，按重要性排序。`,
    '【格式】只输出 JSON 数组，不要解释、不要 markdown 代码块。',
    '   例如：["数学","计算求解"]',
    '',
    existingBlock,
    '',
    '题目：',
    q,
    '',
    '解析：',
    a,
  ].join('\n');
}

/** 单次归类最多写入的标签数（防模型刷出一屏） */
export const MAX_AUTO_TAGS = 4;
